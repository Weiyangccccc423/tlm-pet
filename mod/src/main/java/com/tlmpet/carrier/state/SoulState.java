package com.tlmpet.carrier.state;

/**
 * 女仆"魂"的四种状态（设计文档 §12.6.1）。
 * <p>
 * 这个状态机的唯一目的，是<b>锁死复制路径</b>。玩家的情感寄托必须恒为同一个她，
 * 而"同一个"这件事无法靠实体 UUID 表达（每次注入都会重新分配），
 * 也无法靠"她在不在世界上"表达（她可能正躺在桌宠里）。所以需要一个显式状态。
 *
 * <pre>
 *   NONE ──收服/祭坛合成──▶ IN_WORLD ──抽离──▶ CARRIED ──取出胶卷──▶ FILM_HELD
 *     ▲                                                                   │
 *     └──────────────── 放手仪式（祭坛）／宣告失散 ─────────────────────────┘
 *                                     ▲
 *                                     └── 使用胶卷召唤 ──▶ IN_WORLD
 * </pre>
 *
 * <b>两条关键约束</b>：
 * <ol>
 *   <li>{@code CARRIED} 下<b>不能直接放手</b>。必须先取出胶卷进入 {@code FILM_HELD}。
 *       胶卷既是信物，也是放手仪式的钥匙 —— 这让"告别"成为一次需要亲手递交的动作。</li>
 *   <li>{@code CARRIED → FILM_HELD} 是<b>单向</b>的，且同一时刻只能存在一张她的胶卷。
 *       否则"两张胶卷 = 两只她"，整个唯一性规则会被从内部攻破（风险 R20）。</li>
 * </ol>
 */
public enum SoulState {
    /**
     * 未拥有女仆。可收服，或通过祭坛合成一只<b>全新</b>的（新 {@code maidId}，不继承任何记忆）。
     */
    NONE,

    /**
     * 她以实体形式存在于某个世界。允许：抽离（→ {@link #CARRIED}）、仆从铃世界内召回。
     */
    IN_WORLD,

    /**
     * 她在桌宠里。允许：迎回（→ {@link #IN_WORLD}）、取出胶卷（→ {@link #FILM_HELD}）。
     * <p>
     * 注意此时<b>她不在任何世界</b>，所以与"世界内召回"无关。
     */
    CARRIED,

    /**
     * 她以胶卷形式在玩家手中。允许：使用胶卷召唤她（→ {@link #IN_WORLD}）、
     * 在祭坛举行放手仪式（→ {@link #NONE}）。
     * <p>
     * 进入此状态后桌宠侧<b>不再提供迎回</b>，这是防止重复发卷的关键。
     */
    FILM_HELD
}
